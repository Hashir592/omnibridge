/**
 * Generates the committed API contract files from the route registry (ADR-004):
 *   packages/contract/openapi.json        what the web server actually registers
 *   packages/contract/src/client/schema.ts  openapi-typescript types for the typed client
 *
 *   pnpm contract:gen     write both files
 *   pnpm contract:check   fail if either file differs from what the registry produces
 *
 * Dev-only: excluded from the production build (tsconfig.build.json).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createLogger } from '@omnibridge/logger';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';
import { buildWebApp } from './app.ts';

const contractDir = new URL('../../../packages/contract/', import.meta.url);
const targets = {
  openapi: new URL('openapi.json', contractDir),
  schema: new URL('src/client/schema.ts', contractDir),
};

async function pretty(text: string, file: URL): Promise<string> {
  const path = fileURLToPath(file);
  const config = (await resolveConfig(path)) ?? {};
  return format(text, { ...config, filepath: path });
}

async function generate(): Promise<Record<keyof typeof targets, string>> {
  const app = buildWebApp({
    logger: createLogger({ service: 'contract-gen', version: '0', level: 'silent' }),
    version: '0',
    openapi: true,
    checks: { dbMain: () => Promise.resolve(true), dbPii: () => Promise.resolve(true) },
  });
  await app.ready();
  const document = app.swagger();
  await app.close();

  const header =
    '// Generated by `pnpm contract:gen` from packages/contract. Do not edit by hand.\n';
  const types = astToString(await openapiTS(document as OpenAPI3, { alphabetize: true }));
  return {
    openapi: await pretty(JSON.stringify(document), targets.openapi),
    schema: await pretty(header + types, targets.schema),
  };
}

async function readOrEmpty(file: URL): Promise<string> {
  try {
    return await readFile(file, 'utf8');
  } catch {
    return '';
  }
}

const check = process.argv.includes('--check');
const output = await generate();
const stale: string[] = [];
for (const key of Object.keys(targets) as (keyof typeof targets)[]) {
  const file = targets[key];
  if (check) {
    if ((await readOrEmpty(file)).replaceAll('\r\n', '\n') !== output[key]) {
      stale.push(fileURLToPath(file));
    }
  } else {
    await writeFile(file, output[key]);
  }
}
if (stale.length > 0) {
  console.error(
    `contract: generated files are out of date:\n  ${stale.join('\n  ')}\n` +
      'Run `pnpm contract:gen` and commit the result.',
  );
  process.exitCode = 1;
} else {
  console.log(check ? 'contract: generated files are up to date' : 'contract: files written');
}
